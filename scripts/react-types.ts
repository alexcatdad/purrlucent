// Writes dist/react.d.ts from the Custom Elements Manifest: JSX types for React
// 19, which sets custom element props as properties and listens to their events
// through on<event-name> props. An app loads them with
// `import type {} from "purrlucent/react"`. dist/react.js is an empty module, so
// the entry also resolves at run time.
//
// usage: bun scripts/react-types.ts (after `cem analyze`)
import { readFileSync, writeFileSync } from "node:fs";

export const OUT = "dist/react.d.ts";

type Declaration = {
  name: string;
  tagName?: string;
  attributes?: { fieldName?: string }[];
  members?: {
    kind: string;
    name: string;
    static?: boolean;
    privacy?: string;
    readonly?: boolean;
  }[];
  events?: { name: string; type?: { text: string } }[];
};
export type Manifest = {
  modules: { path: string; declarations?: Declaration[] }[];
};

const union = (names: string[]) =>
  names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "never";

/** The declaration file for every element in the manifest. */
export function reactTypes(manifest: Manifest): string {
  const imports: string[] = [];
  const entries: string[] = [];
  for (const module of manifest.modules) {
    const from = `./types/${module.path.replace(/^src\//, "").replace(/\.ts$/, ".js")}`;
    for (const d of module.declarations ?? []) {
      if (!d.tagName) continue;
      imports.push(`import type { ${d.name} } from "${from}";`);
      // Attributes plus property-only fields (such as an array), which React
      // sets as properties too. Private state (a leading underscore) is not
      // part of the element's API.
      const props = [
        ...new Set(
          [
            ...(d.attributes ?? []).map((a) => a.fieldName),
            ...(d.members ?? [])
              .filter(
                (m) =>
                  m.kind === "field" &&
                  !m.static &&
                  !m.readonly &&
                  (m.privacy ?? "public") === "public",
              )
              .map((m) => m.name),
          ].filter((f): f is string => !!f && !f.startsWith("_")),
        ),
      ];
      // The analyzer also lists a helper's `new CustomEvent(name)` as an event
      // named "name"; every real event is pl-*. Its type comes from the
      // `@fires {CustomEvent<…>}` tag; an untyped one is a plain CustomEvent.
      const events = new Map<string, string>();
      for (const e of d.events ?? [])
        if (e.name.startsWith("pl-") && !events.get(e.name)?.includes("<"))
          events.set(e.name, e.type?.text || "CustomEvent");
      const map = [...events].map(
        ([name, type]) => `${JSON.stringify(name)}: ${type}`,
      );
      entries.push(
        `      "${d.tagName}": PlElement<${d.name}, ${union(props)}, ${map.length ? `{ ${map.join("; ")} }` : "{}"}>;`,
      );
    }
  }
  return `// Generated by scripts/react-types.ts from the custom elements manifest.
// JSX types for React 19: props are set as properties, and each event is an
// on<event-name> prop, for example onpl-change.
import type { HTMLAttributes, RefAttributes } from "react";
${[...new Set(imports)].join("\n")}

type PlElement<E, P extends keyof E, V> = HTMLAttributes<E> &
  RefAttributes<E> &
  Partial<Pick<E, P>> & {
    [K in keyof V as \`on\${K & string}\`]?: (event: V[K]) => void;
  };

declare module "react" {
  namespace JSX {
    interface IntrinsicElements {
${entries.join("\n")}
    }
  }
}
`;
}

if (import.meta.main) {
  const manifest = JSON.parse(
    readFileSync("dist/custom-elements.json", "utf8"),
  ) as Manifest;
  writeFileSync(OUT, reactTypes(manifest));
  writeFileSync("dist/react.js", "export {};\n");
}
