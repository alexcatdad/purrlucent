// Builds src/tokens/tokens.css from design/palette.json and src/tokens/materials.css.
// Run with `bun src/tokens/generate.ts`; `bun run build` does it first.
import { readFileSync, writeFileSync } from "node:fs";

interface Role {
  light: string;
  dark: string;
  lightMoreContrast: string;
  darkMoreContrast: string;
}

interface Palette {
  roles: Record<string, Role>;
  glassTint: { light: string; dark: string };
  glassBlur: number;
}

const dir = import.meta.dirname;
const palette: Palette = JSON.parse(
  readFileSync(`${dir}/../../design/palette.json`, "utf8"),
);

const kebab = (name: string) =>
  name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
// palette.json keeps plain oklch(L C H / A); Stylelint's standard config wants
// percentage lightness and alpha and a deg hue.
const modern = (value: string) =>
  value.replace(
    /oklch\(([\d.]+) ([\d.]+) ([\d.]+)(?: \/ ([\d.]+))?\)/g,
    (_, l, c, h, a) =>
      `oklch(${Number((l * 100).toFixed(4))}% ${c} ${h}deg${a ? ` / ${Number((a * 100).toFixed(4))}%` : ""})`,
  );
const lightDark = (light: string, dark: string) =>
  `light-dark(${modern(light)}, ${modern(dark)})`;
const block = (declarations: string[], indent: number) =>
  declarations.map((d) => `${" ".repeat(indent)}${d}`).join("\n");

const roles = Object.entries(palette.roles);
const color = roles.map(
  ([name, r]) => `--purr-color-${kebab(name)}: ${lightDark(r.light, r.dark)};`,
);
const colorMoreContrast = roles.map(
  ([name, r]) =>
    `--purr-color-${kebab(name)}: ${lightDark(r.lightMoreContrast, r.darkMoreContrast)};`,
);

const fontSizes = {
  caption: "0.75rem",
  footnote: "0.8125rem",
  body: "1rem",
  headline: "1.0625rem",
  title3: "1.25rem",
  title2: "1.375rem",
  title1: "1.75rem",
};
const radii = { small: "0.375rem", medium: "0.625rem", large: "1rem" };
const durations = { fast: "120ms", base: "240ms" };

const type = [
  `--purr-font-family: system-ui, "Segoe UI", roboto, "Helvetica Neue", arial, sans-serif;`,
  ...Object.entries(fontSizes).map(
    ([name, size]) => `--purr-font-size-${name}: ${size};`,
  ),
];
// 4px steps, in rem so spacing follows text zoom.
const space = Array.from(
  { length: 8 },
  (_, i) => `--purr-space-${i + 1}: ${(i + 1) * 0.25}rem;`,
);
const shape = Object.entries(radii).map(
  ([name, size]) => `--purr-radius-${name}: ${size};`,
);
const motion = Object.entries(durations).map(
  ([name, ms]) => `--purr-duration-${name}: ${ms};`,
);
const glass = [
  `--purr-glass-tint: ${lightDark(palette.glassTint.light, palette.glassTint.dark)};`,
  `--purr-glass-blur: ${palette.glassBlur}px;`,
];

const tokens = `/* Generated by src/tokens/generate.ts from design/palette.json. Do not edit. */
@layer purr.tokens {
  :root {
    color-scheme: light dark;

${block([...color, ...type, ...space, ...shape, ...motion, ...glass], 4)}
  }

  @media (prefers-contrast: more) {
    :root {
${block(colorMoreContrast, 6)}
    }
  }

  @media (prefers-reduced-motion: reduce) {
    :root {
${block(
  Object.keys(durations).map((name) => `--purr-duration-${name}: 0ms;`),
  6,
)}
    }
  }
}

`;

const materials = readFileSync(`${dir}/materials.css`, "utf8");
const output = `${dir}/tokens.css`;
writeFileSync(output, tokens + materials);
// Keep the generated file in the repository's formatting so fmt:check stays green.
Bun.spawnSync(["bun", "fmt", output]);
